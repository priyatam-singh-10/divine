              const now = new Date();
              let target = new Date(Date.UTC(now.getUTCFullYear(), 2, 21, 18, 30, 0)); // March 22 00:00 IST = March 21 18:30 UTC
              if (now >= target) {
                target = new Date(Date.UTC(now.getUTCFullYear() + 1, 2, 21, 18, 30, 0));
