            // Find first input to focus (Student's Name)
            const firstInput = document.getElementById('name');

            // Add click listener to ALL buttons with the class
            document.querySelectorAll('.scroll-to-form-btn').forEach(button => {
                button.addEventListener('click', function (e) {
                    // Optional: prevent default if it's not a link/button with href
                    // e.preventDefault();  // uncomment only if needed

                    // 1. Smooth scroll to center of form
                    formContainer.scrollIntoView({
                        behavior: 'smooth',
                        block: 'center'  // centers form in viewport (best UX)
                    });

                    // 2. Focus first input after scroll completes
                    setTimeout(() => {
                        if (firstInput) {
                            firstInput.focus();
                            // Nice visual feedback
                            firstInput.classList.add('ring-4', 'ring-brand-gold', 'ring-opacity-50');
                            setTimeout(() => {
                                firstInput.classList.remove('ring-4', 'ring-brand-gold', 'ring-opacity-50');
                            }, 1800);
                        }
                    }, 700); // 700ms delay — adjust if scroll feels too fast/slow
                });
            });
        });

        // Demo countdown – in real use, set actual expiry time
        let timeLeft = 15 * 60; // 15 minutes
        const countdownEl = document.getElementById('countdown-display');

        function updateCountdown() {
        if (timeLeft <= 0) {
            countdownEl.textContent = "00:00";
            return;
        }

        const minutes = Math.floor(timeLeft / 60);
        const seconds = timeLeft % 60;

        countdownEl.textContent = `${minutes.toString().padStart(2, '0')}:${seconds
            .toString()
            .padStart(2, '0')}`;

        timeLeft--;
        }

        setInterval(updateCountdown, 1000);
        updateCountdown();

    </script>
    
