    (() => {
        const config = window.AI_WEALTH_INQUIRY;
        const form = document.getElementById('regForm');
        const submitBtn = form.querySelector('button[type="submit"]');
        const originalBtnHtml = submitBtn.innerHTML;

        let isSubmitting = false;

        form.addEventListener('submit', async function (event) {
            event.preventDefault();

            // script.js wala purana K-GOD submit handler execute na ho
            event.stopImmediatePropagation();

            if (isSubmitting) return;

            isSubmitting = true;
            submitBtn.disabled = true;
            submitBtn.innerHTML = 'REGISTERING...';

            try {
                // Saare form fields automatically jayenge
                const formData = new FormData(form);
                formData.append('page', config.page);
                formData.append('submitted', '1');

                // AJAX POST to ai.wealth.inquiry.save
                const response = await fetch(config.url, {
                    method: 'POST',
                    body: formData,
                    credentials: 'same-origin',
                    headers: {
                        'X-CSRF-TOKEN': config.token,
                        'X-Requested-With': 'XMLHttpRequest',
                        'Accept': 'application/json'
                    }
                });

                const result = await response.json().catch(() => ({}));

                const requestFailed =
                    !response.ok ||
                    result.status === false ||
                    result.success === false;

                if (requestFailed) {
                    let errorMessage = result.message;

                    if (result.errors) {
                        errorMessage = Object.values(result.errors).flat()[0];
                    }

                    if (response.status === 419) {
                        errorMessage = 'Session expire ho gaya hai. Page refresh karke dobara try karein.';
                    }

                    throw new Error(
                        errorMessage || 'Registration failed. Please try again.'
                    );
                }

                // Insert/save successful
                form.reset();

                // Existing success modal open karo
                const modal = document.getElementById('successModal');
                const card = document.getElementById('successCard');

                if (modal) {
                    modal.classList.remove('hidden');
                    modal.classList.add('flex');
                    document.body.style.overflow = 'hidden';

                    requestAnimationFrame(() => {
                        modal.classList.add('is-open');
                        modal.classList.remove('opacity-0');

                        if (card) {
                            card.classList.remove('scale-95', 'opacity-0');
                        }
                    });
                }

            } catch (error) {
                alert(error.message || 'Network error. Please try again.');
            } finally {
                isSubmitting = false;
                submitBtn.disabled = false;
                submitBtn.innerHTML = originalBtnHtml;
            }
        }, true);
    })();
