  // ---------- FOMO popup triggers ----------
  let fomoShown = false;
  function showFomo() {
    if (fomoShown) return;
    if (document.getElementById('enrollModal').classList.contains('open')) return;
    if (document.getElementById('thankYouPopup').classList.contains('open')) return;
    fomoShown = true;
    openModal('fomo');
  }
  setTimeout(showFomo, 5000);
  document.addEventListener('mouseout', e => { if (!e.relatedTarget && e.clientY <= 0) showFomo(); });
  let maxScroll = 0;
  window.addEventListener('scroll', () => {
    const pct = (window.scrollY / (document.body.scrollHeight - window.innerHeight)) * 100;
    if (pct > maxScroll) maxScroll = pct;
    if (maxScroll > 60 && pct < 20) showFomo();
  });

  // ---------- Smooth anchor scroll ----------
  document.querySelectorAll('a[href^="#"]').forEach(a => {
    a.addEventListener('click', e => {
      const target = document.querySelector(a.getAttribute('href'));
      if (target) {
        e.preventDefault();
