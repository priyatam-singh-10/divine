      headers: {
        'Content-Type': 'application/json',
        'X-CSRF-TOKEN': CSRF_TOKEN,
        'Accept': 'application/json'
      },
      body: JSON.stringify(collectInquiryData(submitted))
    })
      .then(res => res.json())
      .then(function (res) {
        saveInFlight = false;
        if (res && res.inquiry_id) currentInquiryId = String(res.inquiry_id);
        if (typeof onSuccess === 'function') onSuccess(res);
      })
      .catch(function () {
        saveInFlight = false;
        if (typeof onError === 'function') onError();
      });
  }

  function schedulePartialSave() {
    clearTimeout(saveTimer);
    saveTimer = setTimeout(function () {
      if (canSaveInquiry()) saveInquiry(false);
    }, 800);
