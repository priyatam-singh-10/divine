        function canSaveInquiry(source) {
            const data = collectInquiryData(source, false);
            return nameRegex.test((data.fullName || '').trim()) && phoneRegex.test((data.mobile || '').trim());
        }

        function saveInquiry(source, submitted, onSuccess, onError) {
            if (!canSaveInquiry(source) && !submitted) {
                return;
            }

            const payload = collectInquiryData(source, submitted);

            if (saveInFlight) {
                queuedSave = { source: source, submitted: submitted, onSuccess: onSuccess, onError: onError };
                return;
            }

            saveInFlight = true;
            $.ajax({
                url: SAVE_URL,
                type: 'POST',
                data: payload,
                success: function (res) {
                    saveInFlight = false;

                    if (res && res.status === 'submitted') {
                        queuedSave = null;
                        clearInquirySession();
                        if (typeof onSuccess === 'function') onSuccess(res);
                        return;
                    }

                    if (res && res.inquiry_id) {
                        setInquiryId(res.inquiry_id);
                    }

                    if (typeof onSuccess === 'function') onSuccess(res);

                    if (queuedSave) {
                        const next = queuedSave;
                        queuedSave = null;
                        saveInquiry(next.source, next.submitted, next.onSuccess, next.onError);
                    }
                },
                error: function (xhr) {
                    saveInFlight = false;
                    if (typeof onError === 'function') onError(xhr);
                }
            });
        }

