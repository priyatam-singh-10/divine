        function validateNameField(input, errorEl) {
            const value = input.value.trim();
            if (value === '') {
                errorEl.textContent = 'Full Name is required';
                errorEl.classList.add('show');
                input.classList.add('is-invalid');
                input.classList.remove('is-valid');
                return false;
            }
            if (value.length < 3) {
                errorEl.textContent = 'Name must be at least 3 characters';
                errorEl.classList.add('show');
                input.classList.add('is-invalid');
                input.classList.remove('is-valid');
                return false;
            }
            if (!/^[A-Za-z\s.'-]+$/.test(value)) {
                errorEl.textContent = 'Name can only contain letters, spaces, dots, hyphens and apostrophes';
                errorEl.classList.add('show');
                input.classList.add('is-invalid');
                input.classList.remove('is-valid');
                return false;
            }
            errorEl.textContent = '';
            errorEl.classList.remove('show');
            input.classList.remove('is-invalid');
            input.classList.add('is-valid');
            return true;
        }

